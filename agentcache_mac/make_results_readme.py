"""
make_results_readme.py — assemble agentcache_mac/RESULTS.md from the matrix JSONL.

Reads results/matrix/*.jsonl (produced by run_all.py) and emits a single Markdown report:
  - run config + the (mandatory) no-vLLM caveat
  - per-(model, precision): TTFT cold@each-prompt-length vs the single inject value + speedup
  - the headline "cold grows with prompt length, inject stays flat" table
  - quality: coherent / task-check pass, cold vs inject, by precision (quant vs non-quant)
  - precision coverage (which int8/int4 cells actually ran on this MPS build)

Usage:
  python agentcache_mac/make_results_readme.py [matrix_dir] [out_md]
"""

import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
MATRIX_DIR = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "results" / "matrix"
OUT_MD = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / "RESULTS.md"

DTYPE_ORDER = ["fp16", "bf16", "int8", "int4"]
DTYPE_KIND = {"fp16": "non-quant", "bf16": "non-quant", "int8": "quant", "int4": "quant"}


def load():
    recs = []
    for f in sorted(MATRIX_DIR.glob("*.jsonl")):
        for line in f.read_text().splitlines():
            line = line.strip()
            if line:
                recs.append(json.loads(line))
    return recs


def mean(xs):
    xs = [x for x in xs if x is not None]
    return statistics.mean(xs) if xs else float("nan")


def pct(recs, key):
    vals = [r["checks"][key] for r in recs if "checks" in r]
    return 100 * sum(vals) / len(vals) if vals else float("nan")


def main():
    recs = load()
    if not recs:
        print(f"No records in {MATRIX_DIR}")
        return

    ok = [r for r in recs if r.get("mode") in ("cold", "inject")]
    errors = [r for r in recs if r.get("mode") == "ERROR"]

    models = sorted({r["model"] for r in ok})
    dtypes = [d for d in DTYPE_ORDER if d in {r["dtype"] for r in ok}]
    plabels = sorted({r["sys_prompt_label"] for r in ok if r["mode"] == "cold"},
                     key=lambda x: int(x))

    # index: (model, dtype, mode, plabel) -> list of records
    idx = defaultdict(list)
    for r in ok:
        idx[(r["model"], r["dtype"], r["mode"], r.get("sys_prompt_label", "-"))].append(r)

    sys_tokens = {}  # plabel -> token count (from any cold record)
    for r in ok:
        if r["mode"] == "cold":
            sys_tokens[r["sys_prompt_label"]] = r.get("sys_prompt_tokens")

    L = []
    w = L.append
    w("# AgentCache on Apple Silicon — Results\n")
    w("Generated by `make_results_readme.py` from `results/matrix/*.jsonl` "
      "(produced by `run_all.py`).\n")

    w("> **⚠️ HF/MPS, not vLLM.** These numbers come from HuggingFace Transformers on the\n"
      "> Metal backend — no paged attention, fused kernels, continuous batching, APC, or\n"
      "> scheduler prefill-skip. Absolute TTFT is far higher than vLLM and the *speedup\n"
      "> ratios are inflated* because the cold baseline is unoptimized. **Trust the shape**\n"
      "> (cold grows with prompt length; inject stays flat), **not the absolute multiplier**.\n"
      "> The production number lives on vLLM + GPU (see top-level `HANDOFF.md`: ~2.8×).\n")

    # Config
    n_tasks = max(len(idx[(models[0], dtypes[0], "cold", plabels[0])]) if plabels else 0, 0)
    w("## Run configuration\n")
    w(f"- Models: {', '.join(models)}")
    w(f"- Precisions: {', '.join(dtypes)}")
    w(f"- System-prompt lengths: " +
      ", ".join(f"{pl} (~{sys_tokens.get(pl,'?')} tok)" for pl in plabels))
    w(f"- Tasks per cell: {n_tasks}")
    w("- Mode `inject` is run once per (model, precision) — the inject prompt has no system\n"
      "  text, so its TTFT is independent of prompt length; it is compared against each cold point.\n")

    # Headline: TTFT vs prompt length (per model, per precision)
    w("## TTFT — cold vs inject (mean seconds)\n")
    for model in models:
        w(f"### {model}\n")
        for dtype in dtypes:
            cold_pts = {pl: mean([r["ttft_mean_s"] for r in idx[(model, dtype, "cold", pl)]])
                        for pl in plabels}
            inj = mean([r["ttft_mean_s"] for r in idx[(model, dtype, "inject", "-")]])
            if all(v != v for v in cold_pts.values()) and inj != inj:
                continue  # nothing ran for this dtype
            w(f"**{dtype}** ({DTYPE_KIND.get(dtype,'')}) — inject TTFT ≈ "
              f"{inj:.4f}s (flat)\n")
            hdr = "| prompt len | sys tokens | cold TTFT | inject TTFT | speedup |"
            w(hdr)
            w("|---|---|---|---|---|")
            for pl in plabels:
                c = cold_pts[pl]
                sp = (c / inj) if (inj and inj == inj and c == c) else float("nan")
                cdisp = f"{c:.4f}s" if c == c else "—"
                idisp = f"{inj:.4f}s" if inj == inj else "—"
                spdisp = f"{sp:.1f}×" if sp == sp else "—"
                w(f"| {pl} | {sys_tokens.get(pl,'?')} | {cdisp} | {idisp} | {spdisp} |")
            w("")

    # Quality: quant vs non-quant
    w("## Quality — coherence & task-check pass (%)\n")
    w("Does the injected prefix still produce on-task answers, and how does quantization affect it?\n")
    w("| model | precision | kind | mode | coherent % | task-check % |")
    w("|---|---|---|---|---|---|")
    for model in models:
        for dtype in dtypes:
            for mode in ("cold", "inject"):
                rs = [r for pl in (plabels if mode == "cold" else ["-"])
                      for r in idx[(model, dtype, mode, pl)]]
                if not rs:
                    continue
                w(f"| {model} | {dtype} | {DTYPE_KIND.get(dtype,'')} | {mode} | "
                  f"{pct(rs,'coherent'):.0f}% | {pct(rs,'task_check_pass'):.0f}% |")
    w("")

    # Precision coverage
    w("## Precision coverage\n")
    ran = {(r["model"], r["dtype"]) for r in ok}
    w("| model | " + " | ".join(dtypes) + " |")
    w("|---|" + "|".join("---" for _ in dtypes) + "|")
    for model in models:
        cells = []
        for d in dtypes:
            err = any(e["model"] == model and e["dtype"] == d for e in errors)
            cells.append("✅" if (model, d) in ran else ("❌ err" if err else "—"))
        w(f"| {model} | " + " | ".join(cells) + " |")
    if errors:
        w("\n**Errors / skips:**")
        seen = set()
        for e in errors:
            k = (e["model"], e["dtype"])
            if k in seen:
                continue
            seen.add(k)
            w(f"- `{e['model']}` / `{e['dtype']}`: {e.get('error','')[:160]}")
    w("")

    w("## How to read this\n")
    w("- **Headline:** within a row block, `cold TTFT` climbs with prompt length while\n"
      "  `inject TTFT` is one flat value — that gap is the prefill AgentCache eliminates.\n")
    w("- **Speedup column** is inflated vs vLLM (unoptimized cold baseline). The *trend*\n"
      "  across prompt length is the real signal.\n")
    w("- **Quality table:** inject should track cold on coherence/task-check; a drop in\n"
      "  `int8`/`int4` rows is the quantization robustness cost (prefix trained in bf16,\n"
      "  injected into a quantized base).\n")

    OUT_MD.write_text("\n".join(L) + "\n")
    print(f"Wrote {OUT_MD}  ({len(ok)} eval records, {len(errors)} errors)")


if __name__ == "__main__":
    main()
